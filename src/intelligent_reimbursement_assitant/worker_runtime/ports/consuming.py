from typing import Protocol

from intelligent_reimbursement_assitant.execution_state_service.domain.models import QueueDelivery


class QueueConsumer(Protocol):
    async def start(self) -> None: ...
    async def receive(self, limit: int) -> list[QueueDelivery]: ...
    async def reclaim_pending(self, limit: int) -> list[QueueDelivery]: ...
    async def quarantine(self, entry_id: str, reason: str) -> None:
        """Durably record raw fields before ACK, including confirmed missing Jobs."""
        ...

    async def ack(self, entry_id: str) -> None: ...
    async def close(self) -> None: ...
